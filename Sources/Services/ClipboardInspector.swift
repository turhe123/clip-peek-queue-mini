import AppKit
import UniformTypeIdentifiers

/// Broad category of clipboard content, used for the menu-bar icon and tip header.
enum ClipKind {
    case empty, text, richText, image, files, other

    var symbol: String {
        switch self {
        case .empty: return "clipboard"
        case .text: return "doc.plaintext"
        case .richText: return "doc.richtext"
        case .image: return "photo"
        case .files: return "doc.on.doc"
        case .other: return "doc.on.clipboard"
        }
    }

    var title: String {
        switch self {
        case .empty: return "Clipboard is empty"
        case .text: return "Plain Text"
        case .richText: return "Rich Text"
        case .image: return "Image"
        case .files: return "Files"
        case .other: return "Other Data"
        }
    }
}

/// One pasteboard data type with a friendly name and (when inspected) its byte length.
struct ClipTypeInfo: Identifiable {
    let raw: String
    let name: String
    var bytes: Int?
    var id: String { raw }
}

/// Lightweight description built from type names only (never materialises promised data).
struct ClipSummary {
    var kind: ClipKind = .empty
    var itemCount = 0
    var typeNames: [String] = []

    var title: String {
        kind == .files && itemCount > 1 ? "\(itemCount) Files" : kind.title
    }
}

/// Full inspection result shown in the tip: preview, sizes and every type with its byte length.
struct ClipSnapshot {
    var changeCount: Int
    var summary: ClipSummary
    var types: [ClipTypeInfo] = []
    var text: String?
    var characterCount: Int?
    var fileURLs: [URL] = []
    var thumbnail: NSImage?
    var pixelSize: CGSize?
    var image: ImageSource?

    var totalBytes: Int { types.compactMap(\.bytes).reduce(0, +) }
}

/// Where an image on the clipboard comes from; file contents are only read when needed.
enum ImageSource {
    case data(Data)
    case file(URL)

    func load() -> Data? {
        switch self {
        case .data(let data): return data
        case .file(let url): return try? Data(contentsOf: url)
        }
    }
}

/// Reads `NSPasteboard` contents and turns them into summaries, snapshots and thumbnails.
enum ClipboardInspector {
    static let concealedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
    ]
    static let imageTypes: [NSPasteboard.PasteboardType] = [.png, .tiff, NSPasteboard.PasteboardType("public.jpeg"),
                                                            NSPasteboard.PasteboardType("public.heic")]
    private static let richTypes: Set<String> = ["public.rtf", "public.html", "com.apple.flat-rtfd", "com.apple.webarchive"]
    private static let knownNames: [String: String] = [
        "public.utf8-plain-text": "Plain Text", "public.utf16-plain-text": "Plain Text (UTF-16)",
        "public.rtf": "Rich Text (RTF)", "com.apple.flat-rtfd": "Rich Text with Attachments",
        "public.html": "HTML", "public.png": "PNG Image", "public.tiff": "TIFF Image",
        "public.file-url": "File URL", "public.url": "URL", "com.apple.webarchive": "Web Archive",
    ]

    static func friendlyName(_ raw: String) -> String {
        if let known = knownNames[raw] { return known }
        if let desc = UTType(raw)?.localizedDescription, !raw.hasPrefix("dyn.") { return desc.capitalized }
        return raw
    }

    static func isConcealed(_ pb: NSPasteboard) -> Bool {
        (pb.types ?? []).contains { concealedTypes.contains($0.rawValue) }
    }

    /// Classifies the pasteboard using its type list only.
    static func summary(_ pb: NSPasteboard) -> ClipSummary {
        let raws = (pb.types ?? []).map(\.rawValue)
        guard !raws.isEmpty else { return ClipSummary() }
        let set = Set(raws)
        let hasText = set.contains(NSPasteboard.PasteboardType.string.rawValue)
        let hasImage = raws.contains { UTType($0)?.conforms(to: .image) ?? false }
        let kind: ClipKind
        if set.contains(NSPasteboard.PasteboardType.fileURL.rawValue) { kind = .files }
        else if hasImage && !hasText { kind = .image }
        else if !set.isDisjoint(with: richTypes) { kind = .richText }
        else if hasText { kind = .text }
        else if hasImage { kind = .image }
        else { kind = .other }
        var names: [String] = []
        for raw in raws where !raw.hasPrefix("dyn.") && !concealedTypes.contains(raw) {
            let name = friendlyName(raw)
            if !names.contains(name) { names.append(name) }
        }
        return ClipSummary(kind: kind, itemCount: pb.pasteboardItems?.count ?? 0, typeNames: names)
    }

    /// Full read requested by the user: byte length per type, text preview and image data.
    static func snapshot(_ pb: NSPasteboard) -> ClipSnapshot {
        var snap = ClipSnapshot(changeCount: pb.changeCount, summary: summary(pb))
        var seen = Set<String>()
        for item in pb.pasteboardItems ?? [] {
            for type in item.types where seen.insert(type.rawValue).inserted {
                snap.types.append(ClipTypeInfo(raw: type.rawValue, name: friendlyName(type.rawValue),
                                               bytes: item.data(forType: type)?.count))
            }
        }
        if let text = pb.string(forType: .string) {
            snap.characterCount = text.count
            snap.text = String(text.prefix(600))
        }
        snap.fileURLs = fileURLs(pb)
        snap.image = imageSource(pb)
        return snap
    }

    static func fileURLs(_ pb: NSPasteboard) -> [URL] {
        let objects = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true])
        return (objects as? [URL]) ?? []
    }

    /// Image bytes on the pasteboard, or the first copied image file (loaded later, off the main thread).
    static func imageSource(_ pb: NSPasteboard) -> ImageSource? {
        for type in imageTypes { if let data = pb.data(forType: type) { return .data(data) } }
        if let url = fileURLs(pb).first, UTType(filenameExtension: url.pathExtension)?.conforms(to: .image) == true {
            return .file(url)
        }
        return nil
    }

    /// Decodes image data into a small thumbnail and its pixel size. Call off the main thread.
    static func thumbnail(from data: Data, maxSide: CGFloat = 220) -> (NSImage, CGSize)? {
        guard let rep = NSBitmapImageRep(data: data), rep.pixelsWide > 0, rep.pixelsHigh > 0 else { return nil }
        let pixels = CGSize(width: rep.pixelsWide, height: rep.pixelsHigh)
        let scale = min(1, maxSide / max(pixels.width, pixels.height))
        let size = NSSize(width: max(1, (pixels.width * scale).rounded()), height: max(1, (pixels.height * scale).rounded()))
        guard let small = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: Int(size.width), pixelsHigh: Int(size.height),
                                           bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true, isPlanar: false,
                                           colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0),
              let ctx = NSGraphicsContext(bitmapImageRep: small) else { return nil }
        NSGraphicsContext.saveGraphicsState()
        NSGraphicsContext.current = ctx
        ctx.imageInterpolation = .high
        rep.draw(in: NSRect(origin: .zero, size: size))
        NSGraphicsContext.restoreGraphicsState()
        let image = NSImage(size: size)
        image.addRepresentation(small)
        return (image, pixels)
    }

    /// Converts any decodable image data into PNG. Call off the main thread.
    static func pngData(from data: Data) -> Data? {
        guard let rep = NSBitmapImageRep(data: data) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }

    static func bytes(_ count: Int) -> String {
        ByteCountFormatter.string(fromByteCount: Int64(count), countStyle: .file)
    }
}
